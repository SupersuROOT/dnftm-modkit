"""Packs mod folders (mod.json, files/, merge/, art/) into editor/example.js for the editor's "load example" menu.

    python -I build_example.py <out>/example.js <mod folder> [<mod folder> ...]
"""
import base64, json, os, re, sys

out, sources = sys.argv[1], sys.argv[2:]

def load_loose(path):
    text = open(path, encoding="utf-8-sig").read()
    res, i, in_str = [], 0, False
    while i < len(text):
        c = text[i]
        if in_str:
            res.append(c)
            if c == "\\":
                res.append(text[i + 1]); i += 2; continue
            if c == '"': in_str = False
            i += 1; continue
        if c == '"': in_str = True; res.append(c); i += 1; continue
        if text.startswith("//", i):
            while i < len(text) and text[i] != "\n": i += 1
            continue
        if text.startswith("/*", i):
            j = text.find("*/", i + 2); i = len(text) if j < 0 else j + 2; continue
        res.append(c); i += 1
    cleaned = re.sub(r",(\s*[}\]])", r"\1", "".join(res))
    return json.loads(cleaned)

def tree(src, kind):
    base = os.path.join(src, kind); data = {}
    for root, _, files in os.walk(base):
        for f in files:
            p = os.path.join(root, f)
            rel = os.path.relpath(p, base).replace(os.sep, "/")
            data[rel] = load_loose(p) if f.lower().endswith(".json") else open(p, encoding="utf-8").read()
    return data

def assets(src):
    data = {}
    for root, _, files in os.walk(os.path.join(src, "art")):
        for f in files:
            if f.lower().endswith((".png", ".jpg", ".jpeg")):
                p = os.path.join(root, f)
                data[os.path.relpath(p, src).replace(os.sep, "/")] = base64.b64encode(open(p, "rb").read()).decode()
    return data

examples = []
for src in sources:
    examples.append({"folder": os.path.basename(os.path.normpath(src)), "manifest": load_loose(os.path.join(src, "mod.json")),
                     "files": tree(src, "files"), "merges": tree(src, "merge"), "assets": assets(src)})
    print("example:", examples[-1]["folder"], list(examples[-1]["files"]), len(examples[-1]["assets"]), "assets")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_example.py. Example mods for the editor's \"load example\" menu.\n")
    f.write("window.DNFTM_EXAMPLES = ")
    json.dump(examples, f, ensure_ascii=False, indent=1)
    f.write(";\n")
