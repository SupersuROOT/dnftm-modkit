/** ⓘ marker: hover for the explanation, click for a dialog with the full text. */
function tip(key) {
  const text = HELP[key] || key;
  return h('span', { class: 'tip', title: text, tabindex: '0', onclick: e => { e.preventDefault(); e.stopPropagation(); modal('说明', h('div', { style: 'max-width:520px;line-height:1.7' }, text)); } }, 'ⓘ');
}

/** Field label with an ⓘ when an explanation exists. */
function lbl(text, key) {
  return h('label', {}, text, key && HELP[key] ? tip(key) : null);
}

/** Short always-visible note under a field. */
function note(key) {
  return h('div', { class: 'note' }, HELP[key] || key);
}
